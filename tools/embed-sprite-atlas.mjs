#!/usr/bin/env node
/**
 * Embed the approved Sprite AI reference sprites (D49) as base64 data URIs
 * into the client fragment `08b5-sprite-atlas.mjs`. Run after replacing the
 * PNGs in assets/sprite-src/; commit both the sources and the fragment.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const SOURCES = [
  ['round', 'assets/sprite-src/round.png'],
  ['block', 'assets/sprite-src/block.png'],
  ['tall2', 'assets/sprite-src/tall2.png'],
]
const OUT = 'src/client/08b5-sprite-atlas.mjs'

let body = `    // Generated by tools/embed-sprite-atlas.mjs — do not edit by hand.
    // Approved Sprite AI reference sprites (D49), base64-embedded; the 54
    // species variants are composed at runtime (HSL recolor + pattern
    // overlay) into one offscreen atlas. No network, no new dependencies.
    const SF_ATLAS_BASE_DATA = [
`
for (const [name, path] of SOURCES) {
  const b64 = readFileSync(join(process.cwd(), path)).toString('base64')
  body += `      // ${name}\n      'data:image/png;base64,${b64}',\n`
}
body += `    ]
`
writeFileSync(OUT, body, 'utf8')
console.log(`[embed-sprite-atlas] wrote ${OUT} (${SOURCES.length} bases)`)
